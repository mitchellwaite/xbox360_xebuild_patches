#!/usr/bin/env python3
"""Turn the linked code cave into an assembler include for khv_1888.S.

gen_blob.py <cave.bin> <nm output> <out.S>

Writes one KMAKEPATCH block with the cave contents and a .set for every
hook entry point (hk_*), named sfcxbb_<symbol>.
"""
import struct
import sys

BASE = 0x800E1200
CAVE_END = 0x800F0000


def main():
    binf, mapf, outf = sys.argv[1:4]
    data = open(binf, 'rb').read()
    if len(data) % 4:
        data += b'\0' * (4 - len(data) % 4)
    if BASE + len(data) > CAVE_END:
        sys.exit('cave overflow: %d bytes' % len(data))
    syms = {}
    for line in open(mapf):
        parts = line.split()
        if len(parts) == 3 and parts[2].startswith('hk_'):
            syms[parts[2]] = int(parts[0], 16)
    with open(outf, 'w', newline='\n') as f:
        f.write('# Generated by sfcx_bb/build.sh from sfcx_bb/*.c and stubs.S. Do not edit.\n')
        f.write('# %d bytes at 0x%08X\n\n' % (len(data), BASE))
        for name in sorted(syms):
            f.write('.set sfcxbb_%s, 0x%08X\n' % (name, syms[name]))
        f.write('\nKMAKEPATCH 0x%08X\n0:\n' % BASE)
        words = struct.unpack('>%dI' % (len(data) // 4), data)
        for i in range(0, len(words), 8):
            f.write('   .long ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + '\n')
        f.write('9:\n')
    print('%s: %d bytes, %d hooks' % (outf, len(data), len(syms)))


if __name__ == '__main__':
    main()
