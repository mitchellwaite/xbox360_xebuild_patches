#============================================================================
# 1888 SFCX big block (256/512MB Jasper) support
#
# Included from khv_1888.S when sfcx_bigblock is set. Lets 1888 read and
# write the 64MB system area in the stock xeBuild/17559 big block layout
# (the memory unit area isn't used). Every hook checks a flag that
# SfcxInitializeHardware sets only on a big block controller, so small block
# consoles run the stock 1888 code.
#
# The code lives in the unused tail of the last .text page (0x800E1200 up to
# 0x800EFFFF), which the HV copies and maps as kernel code from its static
# page table at HV 0x20000; no new PE section or HV change is needed.
#
# sfcx_bb_1888_blob.S is generated by ../sfcx_bb/build.sh (C engine + asm
# stubs, libxenon toolchain). Design, layout notes and the host-side NAND
# simulator tests are in ../sfcx_bb/README.md.
#============================================================================

.include "sfcx_bb_1888_blob.S"

# SfcxCreateDeviceObject: device extension 0x68C -> 0x6A0 (flag + context)
KMAKEPATCH 0x80076A80
0:
   li %r4, 0x6A0
9:

# SfcxInitializeHardware: decode the controller type and geometry
KMAKEPATCH 0x800762B8
0:
   KMAKEBRANCH sfcxbb_hk_geometry
9:

# SfcxStartFlashPassThrough: DMA requests as register mode sector I/O on BB
KMAKEPATCH 0x80076148
0:
   KMAKEBRANCH sfcxbb_hk_start_tail
9:

# SfcxMountVolume: stock layout mount
KMAKEPATCH 0x80076668
0:
   KMAKEBRANCH sfcxbb_hk_mount
9:

# SfcxTranslateLogicalFlashBlock: FS unit -> 128KB block + slot
KMAKEPATCH 0x80072520
0:
   KMAKEBRANCH sfcxbb_hk_translate
9:

# SfcxFindAvailableFreeFlashBlock: append allocator
KMAKEPATCH 0x80072B88
0:
   KMAKEBRANCH sfcxbb_hk_alloc
9:

# SfcxEraseLogicalFlashBlock: the allocated slot is already erased
KMAKEPATCH 0x80072A70
0:
   KMAKEBRANCH sfcxbb_hk_erase
9:

# SfcxWriteFileDataFlashBlock: type 0x2A unit
KMAKEPATCH 0x800749D0
0:
   KMAKEBRANCH sfcxbb_hk_write_data
9:

# SfcxWriteRootDirectoryFlashBlock: type 0x2C root slot, sequence + 1
KMAKEPATCH 0x80072E80
0:
   KMAKEBRANCH sfcxbb_hk_write_root
9:

# SfcxWriteMobileFile: mobile append log
KMAKEPATCH 0x80072FF8
0:
   KMAKEBRANCH sfcxbb_hk_write_mob
9:

# SfcxVolumeWrite: refused (would erase a 128KB block)
KMAKEPATCH 0x80074B10
0:
   KMAKEBRANCH sfcxbb_hk_volume_write
9:

# SfcxBeginUpdateTransaction: coalescing after the root is loaded
KMAKEPATCH 0x800734A8
0:
   KMAKEBRANCH sfcxbb_hk_begin
9:

# SfcxEndUpdateTransaction: fix open FCBs after a commit
KMAKEPATCH 0x80073310
0:
   KMAKEBRANCH sfcxbb_hk_end
9:
